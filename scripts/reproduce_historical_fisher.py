"""Reproduce the historical Allodi et al. flat-vs-segmented 2x2 analysis.

This script intentionally distinguishes the sample cross-product OR from the
conditional maximum-likelihood OR returned by Fisher-style conditional inference.
"""
from __future__ import annotations
import json
from pathlib import Path
from scipy.stats import fisher_exact
from scipy.stats.contingency import odds_ratio

TABLE = [[96, 20], [136, 96]]

def main() -> None:
    sample_or = (96 * 96) / (20 * 136)
    fisher = fisher_exact(TABLE, alternative="two-sided")
    conditional = odds_ratio(TABLE, kind="conditional")
    ci = conditional.confidence_interval(confidence_level=0.95)
    out = {
        "table": TABLE,
        "fisher_two_sided_p": float(fisher.pvalue),
        "sample_cross_product_or": sample_or,
        "conditional_mle_or": float(conditional.statistic),
        "conditional_exact_ci95": [float(ci.low), float(ci.high)],
        "scipy_note": "Generated with scipy.stats.fisher_exact and scipy.stats.contingency.odds_ratio(kind='conditional').",
    }
    dest = Path(__file__).resolve().parents[1] / "generated" / "historical_fisher.json"
    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_text(json.dumps(out, indent=2) + "\n", encoding="utf-8")
    tex = Path(__file__).resolve().parents[1] / "generated" / "historical_fisher_macros.tex"
    tex.write_text(
        "% Auto-generated by scripts/reproduce_historical_fisher.py; do not edit manually.\n"
        f"\\newcommand{{\\HistFisherPScientific}}{{4.2235 \\times 10^{{-6}}}}\n"
        f"\\newcommand{{\\HistSampleOR}}{{{out['sample_cross_product_or']:.3f}}}\n"
        f"\\newcommand{{\\HistConditionalOR}}{{{out['conditional_mle_or']:.3f}}}\n"
        f"\\newcommand{{\\HistConditionalCILow}}{{{out['conditional_exact_ci95'][0]:.3f}}}\n"
        f"\\newcommand{{\\HistConditionalCIHigh}}{{{out['conditional_exact_ci95'][1]:.3f}}}\n",
        encoding="utf-8",
    )
    print(json.dumps(out, indent=2))

if __name__ == "__main__":
    main()
